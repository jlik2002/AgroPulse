"""Промпты для генерации пояснений.

Единый принцип: модели передаются готовые числа, и её задача — пересказать их
по-русски так, чтобы понял человек без специальной подготовки. Любое вычисление,
оценка или предположение, не переданное во входных данных, является нарушением.

Промпты намеренно подробные. Короткая инструкция вроде «объясни аномалию» даёт
предсказуемо плохой результат: модель либо сыплет техническими обозначениями
вроде z-score без расшифровки, либо уходит в рассуждения о причинах, которых
в данных нет. Поэтому каждый промпт задаёт адресата, структуру ответа, его
длину и явный перечень запретов.

Ограничения продиктованы предметной областью: спутниковый снимок не позволяет
поставить диагноз, а конкретные агротехнические назначения без осмотра поля
могут навредить.
"""

